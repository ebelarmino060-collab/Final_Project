<?php

namespace App\Http\Controllers\Api\V1;

use App\Http\Filters\V1\TicketFilter;
use App\Http\Requests\Api\V1\ReplaceTicketRequest;
use App\Http\Requests\Api\V1\StoreTicketRequest;
use App\Http\Requests\Api\V1\UpdateTicketRequest;
use App\Http\Resources\V1\TicketResource;
use App\Models\Ticket;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Resources\Json\AnonymousResourceCollection;

/**
 * @group Tickets
 *
 * Create, read, update and delete support tickets. Regular users act on the tickets they
 * raised; managers act on any ticket and are the only ones who can assign tickets.
 */
class TicketController extends APIController
{
    /**
     * The relationships a client may request with ?include=...
     *
     * @var list<string>
     */
    protected array $includable = ['author', 'assignee'];

    /**
     * List tickets
     *
     * Returns a paginated list of tickets (15 per page, without descriptions). Supports filtering,
     * searching, sorting and including the author and assignee.
     *
     * @queryParam status string Filter by status. Use a comma for several. Example: open,in_progress
     * @queryParam priority string Filter by priority. Use a comma for several. Example: high,urgent
     * @queryParam search string Search the ticket number and the title. Example: printer
     * @queryParam title string Filter by title. Use * as a wildcard. Example: *printer*
     * @queryParam ticketNumber string Filter by ticket number. Use * as a wildcard. Example: TCK-2026*
     * @queryParam createdBy string Tickets raised by these user ids. Example: 1
     * @queryParam assignedTo string Tickets assigned to these user ids. Example: 2
     * @queryParam createdAt string A date, or a range as from,to. Example: 2026-01-01,2026-12-31
     * @queryParam updatedAt string A date, or a range as from,to. Example: 2026-11-23
     * @queryParam sort string Sort by ticketNumber, title, status, priority, createdAt or updatedAt. Prefix with - for descending. Example: -priority,createdAt
     * @queryParam include string Include related users: author, assignee. Example: author
     * @queryParam page integer The page number. Example: 1
     *
     * @apiResourceCollection App\Http\Resources\V1\TicketResource
     *
     * @apiResourceModel App\Models\Ticket paginate=15
     */
    public function index(TicketFilter $filters): AnonymousResourceCollection
    {
        // Apply the filters from the URL (?status=open, ?search=printer, ?include=author ...)
        // withQueryString() keeps those filters on the pagination links
        return TicketResource::collection(
            Ticket::filter($filters)->paginate()->withQueryString()
        );
    }

    /**
     * Show a ticket
     *
     * Returns one ticket, including its description.
     *
     * @urlParam ticket integer required The ticket id. Example: 1
     *
     * @queryParam include string Include related users: author, assignee. Example: author,assignee
     *
     * @apiResource App\Http\Resources\V1\TicketResource
     *
     * @apiResourceModel App\Models\Ticket
     *
     * @response 404 scenario="Ticket not found" {"errors":[{"status":404,"message":"The resource cannot be found.","source":"App\\Models\\Ticket"}]}
     */
    public function show(Ticket $ticket): TicketResource
    {
        return new TicketResource($ticket->load($this->requestedIncludes()));
    }

    /**
     * Create a ticket
     *
     * Managers can choose any author and an assignee. Regular users can only create tickets
     * for themselves and cannot assign them. The ticket number is generated by the server.
     *
     * @apiResource App\Http\Resources\V1\TicketResource status=201
     *
     * @apiResourceModel App\Models\Ticket
     *
     * @response 422 scenario="Validation failed" {"errors":[{"status":422,"message":"The data.attributes.title field is required.","source":"data.attributes.title"}]}
     */
    public function store(StoreTicketRequest $request): TicketResource|JsonResponse
    {
        // Ask TicketPolicy::store() (checks the ability stored in the token)
        if ($this->isAble('store', Ticket::class)) {
            // mappedAttributes() converts the nested JSON into database columns
            return new TicketResource(
                Ticket::create($request->mappedAttributes())
            );
        }

        return $this->notAuthorized('You are not authorized to create that resource.');
    }

    /**
     * Delete a ticket
     *
     * Regular users can delete the tickets they raised; managers can delete any ticket.
     *
     * @urlParam ticket integer required The ticket id. Example: 1
     *
     * @response 200 {"data":null,"message":"Ticket successfully deleted","status":200}
     * @response 403 scenario="Not your ticket" {"errors":[{"status":403,"message":"You are not authorized to delete that resource.","source":""}]}
     */
    public function destroy(Ticket $ticket): JsonResponse
    {
        if ($this->isAble('delete', $ticket)) {
            $ticket->delete();

            return $this->ok('Ticket successfully deleted');
        }

        return $this->notAuthorized('You are not authorized to delete that resource.');
    }

    /**
     * Replace a ticket
     *
     * Replaces every field of the ticket (managers only). The assignee must be sent, but may be null.
     *
     * @urlParam ticket integer required The ticket id. Example: 1
     *
     * @apiResource App\Http\Resources\V1\TicketResource
     *
     * @apiResourceModel App\Models\Ticket
     *
     * @response 403 scenario="Not a manager" {"errors":[{"status":403,"message":"You are not authorized to replace that resource.","source":""}]}
     */
    public function replace(ReplaceTicketRequest $request, Ticket $ticket): TicketResource|JsonResponse
    {
        if ($this->isAble('replace', $ticket)) {
            $ticket->update($request->mappedAttributes());

            return new TicketResource($ticket);
        }

        return $this->notAuthorized('You are not authorized to replace that resource.');
    }

    /**
     * Update a ticket
     *
     * Changes only the fields that are sent: for example just the status, just the priority,
     * or (managers only) the assignee or the author.
     *
     * @urlParam ticket integer required The ticket id. Example: 1
     *
     * @apiResource App\Http\Resources\V1\TicketResource
     *
     * @apiResourceModel App\Models\Ticket
     *
     * @response 403 scenario="Not your ticket" {"errors":[{"status":403,"message":"You are not authorized to update that resource.","source":""}]}
     */
    public function update(UpdateTicketRequest $request, Ticket $ticket): TicketResource|JsonResponse
    {
        // Ask TicketPolicy::update()
        if ($this->isAble('update', $ticket)) {
            // mappedAttributes() returns only the keys present in the request
            $ticket->update($request->mappedAttributes());

            return new TicketResource($ticket);
        }

        return $this->notAuthorized('You are not authorized to update that resource.');
    }

    /**
     * The allowed relationships the client asked for.
     *
     * @return list<string>
     */
    protected function requestedIncludes(): array
    {
        return array_values(array_filter($this->includable, fn (string $relationship): bool => $this->include($relationship)));
    }
}
