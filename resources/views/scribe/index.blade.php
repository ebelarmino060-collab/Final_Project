        <h1 id="introduction">Introduction</h1>
<p>A versioned JSON:API style REST API for raising, assigning, filtering and resolving support tickets, secured with JWT and token abilities.</p>
<aside>
    <strong>Base URL</strong>: <code>http://localhost:8000</code>
</aside>
<pre><code>This documentation describes version 1 of the Ticket Management API (every URL starts with `/api/v1`). Log in with the manager account `manager@manager.com` / `password` (created by `php artisan db:seed`) to try every endpoint.

&lt;aside&gt;As you scroll, you'll see code examples for working with the API in different programming languages in the dark area to the right (or as part of the content on mobile).
You can switch the language used with the tabs at the top right (or from the nav menu at the top left on mobile).&lt;/aside&gt;</code></pre>

        <h1 id="authenticating-requests">Authenticating requests</h1>
<p>To authenticate requests, include an <strong><code>Authorization</code></strong> header with the value <strong><code>"Bearer {YOUR_ACCESS_TOKEN}"</code></strong>.</p>
<p>All authenticated endpoints are marked with a <code>requires authentication</code> badge in the documentation below.</p>
<p>Log in with <code>POST /api/v1/auth/login</code> and paste the <code>access_token</code> here. Tokens are JWTs that carry your abilities and expire after the configured <code>JWT_TTL</code> (60 minutes by default).</p>

        <h1 id="authentication">Authentication</h1>

    <p>Register, log in, read the current user, refresh and log out. Tokens are JWTs: send them as
<code>Authorization: Bearer {token}</code> on every other request.</p>

